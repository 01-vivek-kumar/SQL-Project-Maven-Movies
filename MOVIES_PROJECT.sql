-- 7. Identify the customers whose total spending on rentals falls within the top 20% of all customers.

WITH CustomerSpending AS (
    SELECT 
        C.CUSTOMER_ID, 
        CONCAT(C.FIRST_NAME, ' ', C.LAST_NAME) AS NAME, 
        SUM(P.AMOUNT) AS TOTAL_SPEND
    FROM payment P
    JOIN customer C ON P.customer_id = C.customer_id
    GROUP BY C.CUSTOMER_ID, NAME
), RankedCustomers AS (
    SELECT *, 
           PERCENT_RANK() OVER (ORDER BY TOTAL_SPEND DESC) AS RANK_PERCENTILE
    FROM CustomerSpending
)
SELECT CUSTOMER_ID, NAME, TOTAL_SPEND
FROM RankedCustomers
WHERE RANK_PERCENTILE <= 0.2  -- Top 20% customers
ORDER BY TOTAL_SPEND DESC;





-- 8. Calculate the running total of rentals per category, ordered by rental count.

WITH CategoryRentalCount AS (
    SELECT 
        C.NAME AS CATEGORY, 
        COUNT(R.RENTAL_ID) AS RENTAL_COUNT
    FROM rental R
    JOIN inventory I ON R.inventory_id = I.inventory_id
    JOIN film_category FC ON I.film_id = FC.film_id
    JOIN category C ON FC.category_id = C.category_id
    GROUP BY C.NAME
)
SELECT 
    CATEGORY, 
    RENTAL_COUNT, 
    SUM(RENTAL_COUNT) OVER (ORDER BY RENTAL_COUNT DESC) AS RUNNING_TOTAL
FROM CategoryRentalCount
ORDER BY RENTAL_COUNT DESC;





-- 9. Find the films that have been rented less than the average rental 
-- count for their respective categories.
WITH FilmRentalCount AS (
    SELECT 
        F.FILM_ID, 
        F.TITLE, 
        C.CATEGORY_ID, 
        C.NAME AS CATEGORY, 
        COUNT(R.RENTAL_ID) AS RENTAL_COUNT
    FROM rental R
    JOIN inventory I ON R.inventory_id = I.inventory_id
    JOIN film F ON I.film_id = F.film_id
    JOIN film_category FC ON F.film_id = FC.film_id
    JOIN category C ON FC.category_id = C.category_id
    GROUP BY F.FILM_ID, F.TITLE, C.CATEGORY_ID, C.NAME
),
CategoryAverageRental AS (
    SELECT 
        CATEGORY_ID, 
        AVG(RENTAL_COUNT) AS AVG_RENTAL_COUNT
    FROM FilmRentalCount
    GROUP BY CATEGORY_ID
)
SELECT 
    FRC.FILM_ID, 
    FRC.TITLE, 
    FRC.CATEGORY, 
    FRC.RENTAL_COUNT, 
    CAR.AVG_RENTAL_COUNT
FROM FilmRentalCount FRC
JOIN CategoryAverageRental CAR ON FRC.CATEGORY_ID = CAR.CATEGORY_ID
WHERE FRC.RENTAL_COUNT < CAR.AVG_RENTAL_COUNT
ORDER BY FRC.CATEGORY, FRC.RENTAL_COUNT;



