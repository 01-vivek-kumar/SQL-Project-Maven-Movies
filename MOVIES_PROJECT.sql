--  a. Write a query using a CTE to find the total number of rentals made each month, considering the 
--  rental_date from the rental table

WITH MONTHLY_RENTALS AS (
    SELECT 
        DATE_PART('year', rental_date) AS rental_year,
        DATE_PART('month', rental_date) AS rental_month,
        COUNT(rental_id) AS total_rentals
    FROM rental
    GROUP BY rental_year, rental_month
    ORDER BY rental_year, rental_month
)
SELECT * FROM MONTHLY_RENTALS;


-- EE' CTE and Self-Join:

--  a. Create a CTE to generate a report showing pairs of actors who have appeared in the same film 
--  together, using the film_actor table.

WITH ACTOR_PAIRS AS (
    SELECT 
        fa1.actor_id AS actor_1,
        fa2.actor_id AS actor_2,
        fa1.film_id
    FROM film_actor fa1
    JOIN film_actor fa2 
        ON fa1.film_id = fa2.film_id 
        AND fa1.actor_id < fa2.actor_id -- Avoid duplicate pairs and self-pairing
)
SELECT 
    a1.first_name || ' ' || a1.last_name AS actor_1,
    a2.first_name || ' ' || a2.last_name AS actor_2,
    f.title AS film_title
FROM ACTOR_PAIRS ap
JOIN actor a1 ON ap.actor_1 = a1.actor_id
JOIN actor a2 ON ap.actor_2 = a2.actor_id
JOIN film f ON ap.film_id = f.film_id;


