-- 4. Identify the top 3 films in each category based on their rental counts.

SELECT TITLE, NAME AS CATEGORY_NAME, RENTAL_COUNT, RENTAL_RANK
FROM (
    SELECT 
        F.TITLE, 
        C.NAME, 
        COUNT(R.RENTAL_ID) AS RENTAL_COUNT, 
        DENSE_RANK() OVER(PARTITION BY C.NAME ORDER BY COUNT(R.RENTAL_ID) DESC) AS RENTAL_RANK
    FROM FILM F 
    JOIN FILM_CATEGORY FC ON F.FILM_ID = FC.FILM_ID 
    JOIN CATEGORY C ON C.CATEGORY_ID = FC.CATEGORY_ID 
    JOIN INVENTORY I ON I.FILM_ID = F.FILM_ID
    JOIN RENTAL R ON R.INVENTORY_ID = I.INVENTORY_ID
    GROUP BY F.TITLE, C.NAME
) A
WHERE RENTAL_RANK <= 3;


-- 5. Calculate the difference in rental counts between each customer's total rentals and the average rentals
-- across all customers.
WITH CustomerRentalCount AS (
    SELECT 
        C.CUSTOMER_ID, 
        CONCAT(C.FIRST_NAME, ' ', C.LAST_NAME) AS CUSTOMER_NAME,
        COUNT(R.RENTAL_ID) AS TOTAL_RENTALS
    FROM rental R
    JOIN customer C ON R.customer_id = C.customer_id
    GROUP BY C.CUSTOMER_ID, CUSTOMER_NAME
)
SELECT 
    CUSTOMER_ID, 
    CUSTOMER_NAME, 
    TOTAL_RENTALS, 
    ROUND(TOTAL_RENTALS - AVG(TOTAL_RENTALS) OVER (), 2) AS RENTAL_DIFF
FROM CustomerRentalCount
ORDER BY RENTAL_DIFF DESC;


